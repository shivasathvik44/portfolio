// Fictional portrait experiment. Shared geometry keeps the hero and Info in sync.
const portrait = [
  "           .:++++:.           ",
  "        .+##########+.        ",
  "       +###@@@@@@@@###+       ",
  "      +##@@@@@@@@@@@@##+      ",
  "     :##@@@@@@@####@@@##:     ",
  "     +#@@@@###++:::+@@@#+     ",
  "     +#@@#+:.......:+@@#+     ",
  "     :#@#:..........:#@#:     ",
  "      +#+..___..___..+#+      ",
  "     :+:+..o.:..:.o..+:+:     ",
  "     :+.+....:..:....+.+:     ",
  "      +.+....:..:....+.+      ",
  "       :+....+__+....+:       ",
  "        +:..........:+       ",
  "        :+..:====:..+:       ",
  "         ++..:--:..++        ",
  "          ++:....:++         ",
  "          :+++++++:          ",
  "          :+.....+:          ",
  "        .++:.....:++.        ",
  "     .:+++.:+...+: .+++:     ",
  "   :++++++..:+.+:..++++++:   ",
  "  ++++++++...:+:...++++++++  ",
  " ++++++++++..:+:..++++++++++ ",
  "+##########+..:..+##########+",
  "############+...+############",
];

export const monogramFontSize = 13;
export const monogramCells = portrait.flatMap((row, y) =>
  [...row].flatMap((character, x) => {
    if (character === " ") return [];
    const seed = x * 7 + y * 11;
    return [{
      id: `portrait-${x}-${y}`,
      x: 240 + (x - (row.length - 1) / 2) * 11,
      y: 46 + y * 9,
      character,
      opacity: character === "." ? 0.45 : 0.65 + (seed % 6) * 0.07,
    }];
  }),
);
